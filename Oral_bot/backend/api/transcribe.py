import logging
import time

from fastapi import APIRouter, File, Header, HTTPException, UploadFile

from core.logging import get_logger, log_event, redact
from services.deepgram_transcriber import transcribe_audio

log = get_logger("transcribe")

router = APIRouter(
    prefix="/transcribe",
    tags=["Transcription"],
)


@router.post("/")
async def transcribe(
    file: UploadFile = File(...),
    # Optional so existing callers are unaffected. Lets this response line up with
    # the frontend's [viva-diag] record for the same oral response.
    x_viva_response_id: str | None = Header(default=None, alias="X-Viva-Response-Id"),
):
    """
    Accepts an uploaded audio file (.webm from MediaRecorder)
    Returns the transcript generated by Deepgram.
    """

    started = time.perf_counter()
    response_id = (x_viva_response_id or "").strip() or "-"

    try:
        audio_bytes = await file.read()

        if not audio_bytes:
            log_event(
                log,
                "transcribe_empty_upload",
                level=logging.WARNING,
                response_id=response_id,
            )
            raise HTTPException(
                status_code=400,
                detail="Empty audio file received.",
            )

        log_event(
            log,
            "transcribe_request_received",
            response_id=response_id,
            bytes=len(audio_bytes),
        )

        result = transcribe_audio(audio_bytes)
        elapsed_ms = round((time.perf_counter() - started) * 1000)

        fields = {
            "response_id": response_id,
            "elapsed_ms": elapsed_ms,
            "chars": len(result.transcript),
            "audio_duration_s": result.duration_s,
            "deepgram_request_id": result.deepgram_request_id,
        }

        if result.transcript:
            log_event(log, "transcribe_ok", **fields)
        else:
            # Audio went in but no text came back. This is the signal behind
            # "my answer wasn't there" reports, so it is a warning, not a 500.
            log_event(log, "transcribe_empty_transcript", level=logging.WARNING, **fields)

        return {
            "success": True,
            "transcript": result.transcript,
        }

    except HTTPException:
        raise

    except Exception as e:
        elapsed_ms = round((time.perf_counter() - started) * 1000)
        log_event(
            log,
            "transcribe_error",
            level=logging.ERROR,
            response_id=response_id,
            elapsed_ms=elapsed_ms,
            error_type=type(e).__name__,
            error=redact(str(e)),
        )
        raise HTTPException(
            status_code=500,
            detail=f"Transcription failed: {str(e)}",
        )
